create or replace view IM_VAULT_DEV.BDV.BENCHMARK_INDEX_SAT(
	LNK_BENCHMARK_INDEX_HKEY,
	LNK_BENCHMARK_INDEX_BKEY,
	BENCHMARK_ID,
	BENCHMARK_NAME,
	FROM_DATE,
	TO_DATE,
	INDEX_ID,
	INDEX_NAME,
	BENCHMARK_INDEX_LAUNCHED_DATE,
	BENCHMARK_INDEX_CLOSED_DATE,
	LOAD_DATETIME
) COMMENT='SAT table to store the descriptive attributes of benchmark & index link'
 as
(
WITH BENCHMARK_INDEX_SAT AS (
SELECT * FROM IM_VAULT_DEV.RDV.BENCHMARK_INDEX_SAT
QUALIFY ROW_NUMBER() OVER(PARTITION BY LNK_BENCHMARK_INDEX_HKEY, LNK_BENCHMARK_INDEX_BKEY, BUS_DATE ORDER BY LOAD_DATETIME DESC)=1
),
BIS AS (
    SELECT DISTINCT
          NULLIF(TO_VARCHAR(LNK_BENCHMARK_INDEX_HKEY), '') AS LNK_BENCHMARK_INDEX_HKEY
        , NULLIF(TO_VARCHAR(LNK_BENCHMARK_INDEX_BKEY), '') AS LNK_BENCHMARK_INDEX_BKEY
        , NULLIF(TO_VARCHAR(BENCHMARK_ID), '') AS BENCHMARK_ID
        , NULLIF(TO_VARCHAR(BENCHMARK_NAME), '') AS BENCHMARK_NAME
        , TRY_TO_DATE(BUS_DATE::VARCHAR,'YYYY-MM-DD') AS FROM_DATE
        , IFNULL(TRY_TO_DATE(lag(BUS_DATE) OVER (PARTITION BY LNK_BENCHMARK_INDEX_HKEY ORDER BY TRY_TO_DATE(BUS_DATE::VARCHAR,'YYYY-MM-DD') desc)::VARCHAR,'YYYY-MM-DD')-1, TO_DATE('9999-12-31', 'YYYY-MM-DD')) AS TO_DATE
        , NULLIF(TO_VARCHAR(INDEX_ID), '') AS INDEX_ID
        , NULLIF(TO_VARCHAR(INDEX_NAME), '') AS INDEX_NAME
        , TRY_TO_DATE(BENCHMARK_INDEX_LAUNCHED_DATE::VARCHAR,'YYYY-MM-DD') AS BENCHMARK_INDEX_LAUNCHED_DATE
        , TRY_TO_DATE(BENCHMARK_INDEX_CLOSED_DATE::VARCHAR,'YYYY-MM-DD') AS BENCHMARK_INDEX_CLOSED_DATE
        , LOAD_DATETIME
    FROM
        BENCHMARK_INDEX_SAT
),
OVR_RECORDS AS (
    SELECT *
    FROM
        (
        SELECT
             HASH_DIFF
            ,OVERRIDE_TYPE
            ,BUSINESS_DATE
            ,LOAD_DATETIME
            ,ATTRIBUTE_NAME
            ,ATTRIBUTE_VALUE
            ,ROW_NUMBER() OVER (PARTITION BY HASH_DIFF, ATTRIBUTE_NAME
                                  ORDER BY LOAD_DATETIME DESC) AS "RECORD_PRIORITY"
        FROM
            IM_VAULT_DEV.NEEDED_A_PLACE.OVERRIDE_LOOKUP
        )
    WHERE "RECORD_PRIORITY" = '1'
),
EXCLUDE_CHECK AS (
    SELECT
        OVR_R.HASH_DIFF
    FROM
        OVR_RECORDS OVR_R
    WHERE OVR_R.OVERRIDE_TYPE = 'Exclude'
),
PIVOT_OVR AS (
    SELECT
        OVR_R.HASH_DIFF
        ,MAX(CASE
             WHEN OVR_R.ATTRIBUTE_NAME = 'NAV_CALC_DATE'
             AND OVR_R.OVERRIDE_TYPE = 'Override'
             THEN OVR_R.ATTRIBUTE_VALUE END) AS OVERRIDE_NAV_CALC_DATE
        ,MAX(CASE
             WHEN OVR_R.ATTRIBUTE_NAME = 'NET_ASSET_VALUE'
             AND OVR_R.OVERRIDE_TYPE = 'Override'
             THEN OVR_R.ATTRIBUTE_VALUE END) AS OVERRIDE_NET_ASSET_VALUE
        ,MAX(CASE
             WHEN OVR_R.ATTRIBUTE_NAME = 'NAV_PER_SHARE'
             AND OVR_R.OVERRIDE_TYPE = 'Override'
             THEN OVR_R.ATTRIBUTE_VALUE END) AS OVERRIDE_NAV_PER_SHARE
        ,MAX(CASE
             WHEN OVR_R.ATTRIBUTE_NAME = 'NET_CAPSTOCK_SHARES_OUTSTANDING'
             AND OVR_R.OVERRIDE_TYPE = 'Override'
             THEN OVR_R.ATTRIBUTE_VALUE END) AS OVERRIDE_NET_CAPSTOCK_SHARES_OUTSTANDING
        ,MAX(OVR_R.LOAD_DATETIME) AS "LOAD_DATETIME"
    FROM
        OVR_RECORDS OVR_R
    WHERE OVR_R.OVERRIDE_TYPE = 'Override'
    GROUP BY OVR_R.HASH_DIFF
)
SELECT
    FNS.FUND_WRAPPER_ID AS FUND_WRAPPER_ID
    ,FNS.FUND_WRAPPER_HKEY AS FUND_WRAPPER_HKEY
    ,FNS.BUSINESS_DATE AS BUSINESS_DATE
    ,COALESCE(CASE
              WHEN OL."OVERRIDE_NAV_CALC_DATE" IS NOT NULL
              AND OL.LOAD_DATETIME > FNS.LOAD_DATETIME
              THEN OL."OVERRIDE_NAV_CALC_DATE"
              ELSE NULL
              END, FNS.NAV_CALC_DATE) AS "NAV_CALC_DATE"
    ,COALESCE(CASE
              WHEN OL."OVERRIDE_NET_ASSET_VALUE" IS NOT NULL
              AND OL.LOAD_DATETIME > FNS.LOAD_DATETIME
              THEN OL."OVERRIDE_NET_ASSET_VALUE"
              ELSE NULL
              END, FNS.NET_ASSET_VALUE) AS "NET_ASSET_VALUE"
     ,COALESCE(CASE
              WHEN OL."OVERRIDE_NAV_PER_SHARE" IS NOT NULL
              AND OL.LOAD_DATETIME > FNS.LOAD_DATETIME
              THEN OL."OVERRIDE_NAV_PER_SHARE"
              ELSE NULL
              END, FNS.NAV_PER_SHARE) AS "NAV_PER_SHARE"
     ,COALESCE(CASE
              WHEN OL."OVERRIDE_NET_CAPSTOCK_SHARES_OUTSTANDING" IS NOT NULL
              AND OL.LOAD_DATETIME > FNS.LOAD_DATETIME
              THEN OL."OVERRIDE_NET_CAPSTOCK_SHARES_OUTSTANDING"
              ELSE NULL
              END, FNS.NET_CAPSTOCK_SHARES_OUTSTANDING) AS "NET_CAPSTOCK_SHARES_OUTSTANDING"
    ,FNS.LOAD_DATETIME
    ,FNS.HASH_DIFF
FROM FUND_WRAPPER_NAV_SAT FNS
LEFT JOIN
    PIVOT_OVR OL
    ON OL.HASH_DIFF = FNS.HASH_DIFF
WHERE
    FNS.HASH_DIFF NOT IN (
        SELECT
            HASH_DIFF
        FROM
            EXCLUDE_CHECK
    )




);